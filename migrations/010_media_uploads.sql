-- ============================================================
-- BROADCAST
-- Migration 010: Media uploads
--
-- File bytes live in a private S3 bucket; only metadata is stored here.
-- media_uploads is one uploaded object: the upload session the client
-- opens, and afterwards the object's verified metadata and lifecycle.
-- message_attachments (from 001) stays the only record of what a message
-- carries; each row now points at the upload that holds its bytes.
--
-- One object may back several messages: a broadcast writes one direct
-- message per recipient, each with its own attachment row, all pointing at
-- the same upload. Access is always decided through the message (chat
-- membership and history window), never through the upload.
--
-- Upload status:
--   pending   session opened, presigned PUT issued, not yet verified
--   ready     object verified (size and type checked against S3)
--   failed    verification refused the object; failure_code says why
--   deleted   removed by the owner or by cleanup; object_deleted_at is
--             set once the S3 object is confirmed gone
--
-- Storage keys are generated by the server (attachments/{opaque id}/...)
-- and never contain user ids, chat ids, phone numbers or file names.
-- ============================================================

CREATE TYPE media_upload_status AS ENUM (
    'pending',
    'ready',
    'failed',
    'deleted'
);

CREATE TABLE media_uploads (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Kept as NULL when the account is deleted so cleanup can still find
    -- and remove the object.
    owner_id          UUID REFERENCES users(id) ON DELETE SET NULL,

    -- Client-generated key: a retried "create upload" returns the session
    -- created by the first attempt.
    client_upload_id  UUID NOT NULL,

    category          attachment_type NOT NULL,
    mime_type         TEXT NOT NULL,
    file_name         TEXT,
    -- Size the client declared; the presigned PUT only accepts exactly
    -- this many bytes.
    declared_size     BIGINT NOT NULL,
    -- Size S3 reports for the stored object, set when verified.
    file_size         BIGINT,

    storage_key       TEXT NOT NULL UNIQUE,

    width             INTEGER,
    height            INTEGER,
    duration_ms       INTEGER,

    status            media_upload_status NOT NULL DEFAULT 'pending',
    failure_code      TEXT,

    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- When the presigned PUT stops working.
    upload_expires_at TIMESTAMPTZ NOT NULL,
    finalized_at      TIMESTAMPTZ,
    -- First time a message used this upload; a used upload is deleted as
    -- soon as no live message or pending broadcast references it.
    attached_at       TIMESTAMPTZ,
    deleted_at        TIMESTAMPTZ,
    object_deleted_at TIMESTAMPTZ,

    CONSTRAINT media_uploads_declared_size_check CHECK (declared_size > 0),
    CONSTRAINT media_uploads_file_size_check CHECK (file_size IS NULL OR file_size > 0),
    CONSTRAINT media_uploads_file_name_length CHECK (file_name IS NULL OR char_length(file_name) <= 255),
    CONSTRAINT media_uploads_dimensions_check
        CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0)),
    CONSTRAINT media_uploads_duration_check CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT media_uploads_ready_check
        CHECK (status <> 'ready' OR (file_size IS NOT NULL AND finalized_at IS NOT NULL)),
    CONSTRAINT media_uploads_failure_check
        CHECK ((status = 'failed') = (failure_code IS NOT NULL)),
    CONSTRAINT media_uploads_deleted_check
        CHECK ((status = 'deleted') = (deleted_at IS NOT NULL))
);

CREATE UNIQUE INDEX media_uploads_owner_client_unique
    ON media_uploads (owner_id, client_upload_id);

-- Cleanup work: everything whose object may still exist in S3.
CREATE INDEX media_uploads_cleanup_idx
    ON media_uploads (status, created_at)
    WHERE object_deleted_at IS NULL;

-- ------------------------------------------------------------
-- Attachments: link to the upload holding the bytes
-- ------------------------------------------------------------

ALTER TABLE message_attachments
    -- Nullable only for rows written before this migration (there are
    -- none); every new attachment sets it.
    ADD COLUMN upload_id UUID
        REFERENCES media_uploads(id)
        ON DELETE RESTRICT,
    ADD COLUMN thumbnail_upload_id UUID
        REFERENCES media_uploads(id)
        ON DELETE RESTRICT;

-- One attachment per message (an album is several messages).
DROP INDEX IF EXISTS message_attachments_message_idx;
CREATE UNIQUE INDEX message_attachments_message_unique
    ON message_attachments (message_id);

CREATE INDEX message_attachments_upload_idx
    ON message_attachments (upload_id)
    WHERE upload_id IS NOT NULL;

CREATE INDEX message_attachments_thumbnail_upload_idx
    ON message_attachments (thumbnail_upload_id)
    WHERE thumbnail_upload_id IS NOT NULL;

-- ------------------------------------------------------------
-- Broadcasts: the shared upload for every recipient message
-- ------------------------------------------------------------

ALTER TABLE broadcast_messages
    ADD COLUMN attachment_upload_id UUID
        REFERENCES media_uploads(id)
        ON DELETE RESTRICT,
    ADD COLUMN thumbnail_upload_id UUID
        REFERENCES media_uploads(id)
        ON DELETE RESTRICT,
    ADD CONSTRAINT broadcast_messages_thumbnail_check
        CHECK (thumbnail_upload_id IS NULL OR attachment_upload_id IS NOT NULL);

CREATE INDEX broadcast_messages_attachment_upload_idx
    ON broadcast_messages (attachment_upload_id)
    WHERE attachment_upload_id IS NOT NULL;

CREATE INDEX broadcast_messages_thumbnail_upload_idx
    ON broadcast_messages (thumbnail_upload_id)
    WHERE thumbnail_upload_id IS NOT NULL;
